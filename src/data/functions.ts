export type FunctionReturns = 'tabla' | 'escalar' | 'condicion' | 'clausula'

export interface FunctionParam {
  name: string
  description: string
}

export interface FunctionDoc {
  name: string
  /** Agrupa la entrada en el menu lateral. */
  category: string
  syntax: string
  parameters: FunctionParam[]
  returns: FunctionReturns
  /** Una frase sobre lo que devuelve o produce. */
  returnsDescription: string
  /** Que hace por dentro: en que momento del orden logico actua y que transforma. */
  description: string
  /** Consulta de ejemplo sobre las tablas del modelo que el motor puede ejecutar. */
  example: string
  /** Texto que se inserta en el editor. */
  snippet: string
}

function fn(
  name: string,
  category: string,
  syntax: string,
  parameters: FunctionParam[],
  returns: FunctionReturns,
  returnsDescription: string,
  description: string,
  example: string,
  snippet: string = `${name}(`,
): FunctionDoc {
  return { name, category, syntax, parameters, returns, returnsDescription, description, example, snippet }
}

